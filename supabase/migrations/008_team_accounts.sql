-- ── SECTION 8: HELPER FUNCTION ───────────────────────────────
-- Returns true if a token exists, is unused, and has not expired.
-- Called by POST /api/register/validate before rendering signup form.

CREATE OR REPLACE FUNCTION is_invite_token_valid(p_token text)
RETURNS boolean AS $$
  SELECT EXISTS (
    SELECT 1 FROM invite_tokens
    WHERE token      = p_token
      AND used       = false
      AND expires_at > now()
  );
$$ LANGUAGE sql SECURITY DEFINER;


